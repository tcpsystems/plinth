// Client code generation from the served schema: clients are generated from
// the served schema index ({prefix}/schema), never hand-written. The rules
// the output must satisfy are in rules/, and codegen_test.go checks them.
// GenerateTypeScript turns a [SchemaIndex] into a self-contained, deterministic
// TypeScript module carrying:
//
//   - per-event payload interfaces derived from each event's JSON Schema
//   - EventDataMap and the discriminated EventEnvelope / WSOutboundFrame unions
//   - streamURL and wsURL builders using the ?topics= and ?last_seq= query
//     parameters
//   - typed Connect-JSON unary RPC helpers for every registered rpc_methods entry

// GenerateTypeScript renders a deterministic TypeScript client module from
// idx. It validates the index first so a malformed served
// schema fails generation instead of emitting broken client code.
func GenerateTypeScript(idx SchemaIndex) ([]byte, error) {
	if strings.TrimSpace(idx.Service) == "" {
		return nil, errors.New("realtime: codegen: schema index service is required")
	}
	if idx.RealtimePrefix == "" || idx.RealtimePrefix[0] != '/' || strings.HasSuffix(idx.RealtimePrefix, "/") {
		return nil, errors.New(`realtime: codegen: realtime_prefix must start with "/" and have no trailing slash, got ` + strconv.Quote(idx.RealtimePrefix))
	}

	events := slices.Clone(idx.Events)
	sort.Slice(events, func(i, j int) bool { return events[i].Kind < events[j].Kind })
	seenKinds := make(map[string]struct{}, len(events))
	parsedSchemas := make([]map[string]any, len(events))
	for i, ev := range events {
		if err := ValidateKind(ev.Kind); err != nil {
			return nil, err
		}
		if err := ValidateTopicPattern(ev.TopicPattern); err != nil {
			return nil, err
		}
		if _, dup := seenKinds[ev.Kind]; dup {
			return nil, errors.New("realtime: codegen: duplicate event kind " + ev.Kind)
		}
		seenKinds[ev.Kind] = struct{}{}
		var obj map[string]any
		if err := json.Unmarshal(ev.Schema, &obj); err != nil || obj == nil {
			return nil, errors.New("realtime: codegen: schema for " + ev.Kind + " must be a JSON object")
		}
		parsedSchemas[i] = obj
	}

	var rpcMethods []string
	if idx.Connect != nil {
		rpcMethods = slices.Clone(idx.Connect.RPCMethods)
		sort.Strings(rpcMethods)
		for _, m := range rpcMethods {
			slash := strings.IndexByte(m, '/')
			if slash <= 0 || slash == len(m)-1 || strings.ContainsAny(m[slash+1:], "/") {
				return nil, errors.New(`realtime: codegen: rpc method must be "pkg.Service/Method", got ` + strconv.Quote(m))
			}
		}
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by github.com/tcpsystems/plinth/realtime from served schema; DO NOT EDIT.\n")
	b.WriteString("// Service: " + idx.Service + " (" + idx.RealtimePrefix + ")\n\n")
	b.WriteString("export const SERVICE = " + strconv.Quote(idx.Service) + " as const;\n")
	b.WriteString("export const REALTIME_PREFIX = " + strconv.Quote(idx.RealtimePrefix) + " as const;\n")
	if idx.REST != nil && idx.REST.OpenAPIPath != "" {
		b.WriteString("export const OPENAPI_PATH = " + strconv.Quote(idx.REST.OpenAPIPath) + " as const;\n")
	}
	if idx.Connect != nil && idx.Connect.DescriptorSetPath != "" {
		b.WriteString("export const DESCRIPTOR_SET_PATH = " + strconv.Quote(idx.Connect.DescriptorSetPath) + " as const;\n")
	}
	b.WriteString("\n")

	for i, ev := range events {
		typeName := pascalKind(ev.Kind) + "EventData"
		renderSchemaInterface(&b, typeName, parsedSchemas[i])
		b.WriteString("\n")
	}

	b.WriteString("export interface EventDataMap {\n")
	for _, ev := range events {
		b.WriteString("  " + strconv.Quote(ev.Kind) + ": " + pascalKind(ev.Kind) + "EventData;\n")
	}
	b.WriteString("}\n\n")

	b.WriteString("export const EVENT_TOPIC_PATTERNS = {\n")
	for _, ev := range events {
		b.WriteString("  " + strconv.Quote(ev.Kind) + ": " + strconv.Quote(ev.TopicPattern) + ",\n")
	}
	b.WriteString("} as const;\n\n")

	if len(events) > 0 {
		b.WriteString("export type EventKind = keyof EventDataMap;\n\n")
		b.WriteString("export interface EventEnvelope<K extends EventKind = EventKind> {\n")
		b.WriteString("  seq: number;\n")
		b.WriteString("  topic: string;\n")
		b.WriteString("  kind: K;\n")
		b.WriteString("  data: EventDataMap[K];\n")
		b.WriteString("}\n\n")
		b.WriteString("export type WSOutboundFrame =\n")
		b.WriteString("  | { [K in EventKind]: { type: \"event\"; seq: number; topic: string; kind: K; data: EventDataMap[K] } }[EventKind]\n")
		b.WriteString("  | { type: \"snapshot\"; seq: number; data: unknown }\n")
		b.WriteString("  | { type: \"reset\"; seq: number; data: { reason: string } }\n")
		b.WriteString("  | { type: \"pong\"; seq: number };\n\n")
	} else {
		b.WriteString("export type EventKind = never;\n\n")
		b.WriteString("export type WSOutboundFrame =\n")
		b.WriteString("  | { type: \"snapshot\"; seq: number; data: unknown }\n")
		b.WriteString("  | { type: \"reset\"; seq: number; data: { reason: string } }\n")
		b.WriteString("  | { type: \"pong\"; seq: number };\n\n")
	}

	b.WriteString("export type WSInboundFrame =\n")
	b.WriteString("  | { type: \"resume\"; seq: number }\n")
	b.WriteString("  | { type: \"ping\"; seq: number }\n")
	b.WriteString("  | { type: \"msg\"; seq?: number; topic?: string; data?: unknown };\n\n")

	b.WriteString("export function streamURL(baseURL: string, topics: readonly string[]): string {\n")
	b.WriteString("  const root = baseURL.replace(/\\/+$/, \"\");\n")
	b.WriteString("  return `${root}${REALTIME_PREFIX}/stream?topics=${encodeURIComponent(topics.join(\",\"))}`;\n")
	b.WriteString("}\n\n")

	b.WriteString("export function wsURL(baseURL: string, topics: readonly string[], lastSeq?: number): string {\n")
	b.WriteString("  const root = baseURL.replace(/^http/, \"ws\").replace(/\\/+$/, \"\");\n")
	b.WriteString("  const q = `topics=${encodeURIComponent(topics.join(\",\"))}`;\n")
	b.WriteString("  return lastSeq && lastSeq > 0 ? `${root}${REALTIME_PREFIX}/ws?${q}&last_seq=${lastSeq}` : `${root}${REALTIME_PREFIX}/ws?${q}`;\n")
	b.WriteString("}\n\n")

	b.WriteString("export const RPC_METHODS = [")
	for i, m := range rpcMethods {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(strconv.Quote(m))
	}
	b.WriteString("] as const;\n")
	b.WriteString("export type RPCMethod = (typeof RPC_METHODS)[number];\n\n")

	b.WriteString("export interface ConnectErrorWire {\n")
	b.WriteString("  code: string;\n")
	b.WriteString("  message?: string;\n")
	b.WriteString("  details?: Array<{ type: string; value?: string; debug?: unknown }>;\n")
	b.WriteString("}\n\n")

	b.WriteString("export async function callRPC<Req = Record<string, unknown>, Resp = unknown>(\n")
	b.WriteString("  baseURL: string,\n")
	b.WriteString("  method: RPCMethod,\n")
	b.WriteString("  request: Req,\n")
	b.WriteString("  opts?: { headers?: Record<string, string>; timeoutMs?: number; signal?: AbortSignal },\n")
	b.WriteString("): Promise<Resp> {\n")
	b.WriteString("  const root = baseURL.replace(/\\/+$/, \"\");\n")
	b.WriteString("  const headers: Record<string, string> = { \"Content-Type\": \"application/json\", \"Connect-Protocol-Version\": \"1\", ...opts?.headers };\n")
	b.WriteString("  if (opts?.timeoutMs && opts.timeoutMs > 0) {\n")
	b.WriteString("    headers[\"Connect-Timeout-Ms\"] = String(Math.floor(opts.timeoutMs));\n")
	b.WriteString("  }\n")
	b.WriteString("  const resp = await fetch(`${root}${REALTIME_PREFIX}/rpc/${method}`, {\n")
	b.WriteString("    method: \"POST\",\n")
	b.WriteString("    headers,\n")
	b.WriteString("    body: JSON.stringify(request ?? {}),\n")
	b.WriteString("    credentials: \"include\",\n")
	b.WriteString("    signal: opts?.signal,\n")
	b.WriteString("  });\n")
	b.WriteString("  if (!resp.ok) {\n")
	b.WriteString("    const err = (await resp.json().catch(() => ({ code: \"unknown\" }))) as ConnectErrorWire;\n")
	b.WriteString("    throw Object.assign(new Error(err.message ?? err.code), { connect: err, status: resp.status });\n")
	b.WriteString("  }\n")
	b.WriteString("  return (await resp.json()) as Resp;\n")
	b.WriteString("}\n")

	return b.Bytes(), nil
}

// GenerateTypeScript renders the TypeScript client module for s's current
// index snapshot.
func (s *Schemas) GenerateTypeScript() ([]byte, error) {
	return GenerateTypeScript(s.Index())
}

// pascalKind converts "run.started" or "item.plan.step.updated" into
// "RunStarted" or "ItemPlanStepUpdated".
func pascalKind(kind string) string {
	var out strings.Builder
	for _, seg := range strings.Split(kind, ".") {
		if seg == "" {
			continue
		}
		out.WriteByte(seg[0] - ('a' - 'A'))
		out.WriteString(seg[1:])
	}
	return out.String()
}

func renderSchemaInterface(b *bytes.Buffer, name string, schema map[string]any) {
	b.WriteString("export interface " + name + " {\n")
	reqSet := map[string]bool{}
	if reqList, ok := schema["required"].([]any); ok {
		for _, r := range reqList {
			if s, ok := r.(string); ok {
				reqSet[s] = true
			}
		}
	}
	props, _ := schema["properties"].(map[string]any)
	keys := make([]string, 0, len(props))
	for k := range props {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		propSchema, _ := props[k].(map[string]any)
		opt := "?"
		if reqSet[k] {
			opt = ""
		}
		b.WriteString("  " + tsPropKey(k) + opt + ": " + schemaTypeToTS(propSchema) + ";\n")
	}
	if addl, ok := schema["additionalProperties"].(bool); !ok || addl {
		if len(keys) == 0 {
			b.WriteString("  [key: string]: unknown;\n")
		}
	}
	b.WriteString("}\n")
}

func tsPropKey(k string) string {
	for i := 0; i < len(k); i++ {
		c := k[i]
		ok := (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || c == '_' || (i > 0 && c >= '0' && c <= '9')
		if !ok {
			return strconv.Quote(k)
		}
	}
	if k == "" {
		return `""`
	}
	return k
}

func schemaTypeToTS(s map[string]any) string {
	if s == nil {
		return "unknown"
	}
	if enums, ok := s["enum"].([]any); ok && len(enums) > 0 {
		parts := make([]string, 0, len(enums))
		for _, e := range enums {
			raw, err := json.Marshal(e)
			if err == nil {
				parts = append(parts, string(raw))
			}
		}
		if len(parts) > 0 {
			return strings.Join(parts, " | ")
		}
	}
	t, _ := s["type"].(string)
	switch t {
	case "string":
		return "string"
	case "number", "integer":
		return "number"
	case "boolean":
		return "boolean"
	case "null":
		return "null"
	case "array":
		items, _ := s["items"].(map[string]any)
		return "Array<" + schemaTypeToTS(items) + ">"
	case "object":
		if _, hasProps := s["properties"].(map[string]any); hasProps {
			var sub bytes.Buffer
			reqSet := map[string]bool{}
			if reqList, ok := s["required"].([]any); ok {
				for _, r := range reqList {
					if str, ok := r.(string); ok {
						reqSet[str] = true
					}
				}
			}
			props := s["properties"].(map[string]any)
			keys := make([]string, 0, len(props))
			for k := range props {
				keys = append(keys, k)
			}
			sort.Strings(keys)
			sub.WriteString("{ ")
			for i, k := range keys {
				if i > 0 {
					sub.WriteString("; ")
				}
				ps, _ := props[k].(map[string]any)
				opt := "?"
				if reqSet[k] {
					opt = ""
				}
				sub.WriteString(tsPropKey(k) + opt + ": " + schemaTypeToTS(ps))
			}
			sub.WriteString(" }")
			return sub.String()
		}
		return "Record<string, unknown>"
	default:
		return "unknown"
	}
}
